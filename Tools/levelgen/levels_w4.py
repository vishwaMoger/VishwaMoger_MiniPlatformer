"""World 4 - Jungle Ruins: dark overgrown temple lit by lanterns and fireflies."""
from levelkit import Level


def temple_hall(L, x0, x1, floor_top, height, lanterns=3):
    """Background wall + ceiling + lanterns: an interior hall standing on existing ground."""
    ceil = floor_top + height + 1
    L.rect(x0, x1, floor_top + 1, ceil - 1, "+")
    L.rect(x0, x1, ceil, ceil + 1, "#")
    step = max(4, (x1 - x0) // (lanterns + 1))
    for i in range(1, lanterns + 1):
        L.put(x0 + i * step, ceil - 2, "L")


