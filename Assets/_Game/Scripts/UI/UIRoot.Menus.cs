        /// <summary>Masks a button to its own shape and sweeps a light band across it.</summary>
        static void AddShine(Button b, float width)
        {
            var mask = b.gameObject.AddComponent<Mask>();
            mask.showMaskGraphic = true;
            var band = UIKit.Image(b.transform, UIArt.ShineBand, new Vector2(0.5f, 0.5f), Vector2.zero, new Vector2(90f, 300f), "Shine");
            band.transform.SetSiblingIndex(0);
            band.gameObject.AddComponent<UIShine>().width = width;
        }

