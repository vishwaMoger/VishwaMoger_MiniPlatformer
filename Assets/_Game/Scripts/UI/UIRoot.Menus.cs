                var logoSize = Portrait ? new Vector2(1080f, 310f) : new Vector2(1150f, 330f);
                logoRt = UIKit.Rect(root, "LogoRoot", new Vector2(0.5f, 1f), new Vector2(0f, Portrait ? -420f : -240f), logoSize);
                var logoImg = UIKit.Image(logoRt, logoSprite, new Vector2(0.5f, 0.5f), Vector2.zero, logoSize, "Logo");
                logoImg.preserveAspect = true;
                logoImg.gameObject.AddComponent<UILogoMotion>();
