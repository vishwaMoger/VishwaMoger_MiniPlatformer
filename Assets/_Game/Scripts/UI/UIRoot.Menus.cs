                float ang = i / 9f * Mathf.PI * 2f + 0.4f;
                var pos = new Vector2(Mathf.Cos(ang) * (720f + (i % 3) * 50f), -250f + Mathf.Sin(ang) * (190f + (i % 2) * 40f));
