        public const int LevelsPerPage = 10;

        void BuildLevelSelect()
        {
            var root = UIKit.Stretch(m_MenuLayer, "LevelSelect");
            int reached = SaveSystem.Data.level;
            int allPages = (SaveSystem.MaxLevels + LevelsPerPage - 1) / LevelsPerPage;
            int pages = Mathf.Clamp((reached - 1) / LevelsPerPage + 2, 1, allPages); // one page past the frontier, to tease
            m_BrowseWorld = Mathf.Clamp(m_BrowseWorld, 0, pages - 1);
            Game.I.SetMenuWorld(Game.WorldForLevel(m_BrowseWorld * LevelsPerPage + 1));

            var back = UIKit.IconButton(root, UIArt.Arrow(2), "grey", new Vector2(0f, 1f), new Vector2(100f, -90f), 110f, () => ShowMenu(MenuScreen.Title), "back");
            var title = UIKit.Text(root, "LEVELS", 52f, new Vector2(0.5f, 1f), new Vector2(0f, -100f), new Vector2(1200f, 90f), TextStyle.Title, UIKit.Gold);
            UIKit.SlideIn(title.rectTransform, new Vector2(0f, 120f));

            var starRt = UIKit.Rect(root, "Stars", new Vector2(1f, 1f), new Vector2(-200f, -90f), new Vector2(320f, 90f));
            UIKit.Panel(starRt, "glass", new Vector2(0.5f, 0.5f), Vector2.zero, new Vector2(320f, 90f));
            UIKit.Image(starRt, UIArt.Star, new Vector2(0.5f, 0.5f), new Vector2(-100f, 0f), new Vector2(56f, 56f));
            UIKit.Text(starRt, SaveSystem.TotalStars().ToString(), 30f, new Vector2(0.5f, 0.5f), new Vector2(30f, 0f), new Vector2(220f, 60f), TextStyle.Heading, UIKit.Gold);

            var panel = UIKit.Rect(FitBox(root, 1420f), "Panel", new Vector2(0.5f, 0.5f), new Vector2(0f, -40f), new Vector2(1380f, 660f));
            UIKit.Panel(panel, "panel", new Vector2(0.5f, 0.5f), Vector2.zero, new Vector2(1380f, 660f));
            int firstLevel = m_BrowseWorld * LevelsPerPage + 1;
            var ribbon = UIKit.Panel(panel, "yellow", new Vector2(0.5f, 1f), new Vector2(0f, -10f), new Vector2(880f, 104f), "Ribbon");
            UIKit.Text(ribbon.transform, $"LEVELS {firstLevel}-{firstLevel + LevelsPerPage - 1}", 34f, new Vector2(0.5f, 0.5f), new Vector2(0f, 4f), new Vector2(860f, 80f), TextStyle.Dark);
            UIKit.PopIn(panel, 0.05f);

            Button first = null;
            for (int i = 0; i < LevelsPerPage; i++)
            {
                int level = firstLevel + i;
                if (level > SaveSystem.MaxLevels) break;
                var pos = new Vector2(((i % 5) - 2) * 250f, i < 5 ? 70f : -190f);
                var card = LevelCard(panel, level, level <= reached, pos);
                UIKit.SlideIn((RectTransform)card.transform, new Vector2(0f, -60f), 0.08f + i * 0.03f);
                if (level == reached || (first == null && card.interactable)) first = card;
            }

            var prevPos = Portrait ? new Vector2(-220f, -400f) : new Vector2(-780f, -40f);
            var nextPos = Portrait ? new Vector2(220f, -400f) : new Vector2(780f, -40f);
            var prev = UIKit.IconButton(root, UIArt.Arrow(2), "blue", new Vector2(0.5f, 0.5f), prevPos, 120f, () => BrowseWorld(-1), "switch");
            var nextBtn = UIKit.IconButton(root, UIArt.Arrow(0), "blue", new Vector2(0.5f, 0.5f), nextPos, 120f, () => BrowseWorld(1), "switch");
            prev.gameObject.SetActive(m_BrowseWorld > 0);
            nextBtn.gameObject.SetActive(m_BrowseWorld < pages - 1);
            UIKit.Text(root, "STARS:  SOLVED  -  FAST  -  AT OR UNDER PAR SLIDES", 18f, new Vector2(0.5f, 0f), new Vector2(0f, 40f), new Vector2(1400f, 30f), TextStyle.Body, new Color(1, 1, 1, 0.8f));
            Select(first != null ? first : back);
        }

        void BrowseWorld(int dir)
        {
            m_BrowseWorld = Mathf.Max(0, m_BrowseWorld + dir);
            ShowMenu(MenuScreen.LevelSelect);
        }

        Button LevelCard(Transform parent, int level, bool unlocked, Vector2 pos)
        {
            var size = new Vector2(220f, 230f);
            var img = UIKit.Panel(parent, unlocked ? "card" : "dim_card", new Vector2(0.5f, 0.5f), pos, size, "Level" + level);
            img.raycastTarget = true;
            var btn = img.gameObject.AddComponent<Button>();
            btn.transition = Selectable.Transition.ColorTint;
            var colors = btn.colors;
            colors.highlightedColor = new Color(1f, 1f, 0.9f);
            colors.pressedColor = new Color(0.85f, 0.85f, 0.8f);
            colors.disabledColor = new Color(0.8f, 0.8f, 0.85f);
            colors.selectedColor = new Color(1f, 1f, 0.9f);
            btn.colors = colors;
            btn.interactable = unlocked;
            var fx = img.gameObject.AddComponent<UIButtonFX>();
            fx.sound = "confirm";
            int captured = level;
            btn.onClick.AddListener(() => Game.I.PlayLevel(captured));

            bool current = level == SaveSystem.Data.level;
            if (current) fx.pulse = 1f;
            var header = UIKit.Panel(img.transform, !unlocked ? "track" : current ? "yellow" : "green", new Vector2(0.5f, 1f), new Vector2(0f, -62f), new Vector2(180f, 96f), "Header");
            UIKit.Text(header.transform, level.ToString(), 48f, new Vector2(0.5f, 0.5f), new Vector2(0f, 5f), new Vector2(180f, 80f), current ? TextStyle.Dark : TextStyle.Heading);
            if (!unlocked)
            {
                UIKit.Image(img.transform, UIArt.Lock, new Vector2(0.5f, 0f), new Vector2(0f, 62f), new Vector2(64f, 74f));
                return btn;
            }
            int mask = SaveSystem.Data.stars[level];
            for (int st = 0; st < 3; st++)
            {
                bool got = (mask & (1 << st)) != 0;
                UIKit.Image(img.transform, got ? UIArt.Star : UIArt.StarEmpty, new Vector2(0.5f, 0f), new Vector2((st - 1) * 58f, 58f + (st == 1 ? 10f : 0f)), new Vector2(54f, 54f));
            }
            return btn;
        }

