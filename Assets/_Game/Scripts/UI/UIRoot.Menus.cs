            UIKit.Panel(panel, "panel", new Vector2(0.5f, 0.5f), Vector2.zero, new Vector2(900f, 760f));
            UIKit.Panel(panel, "card", new Vector2(0.5f, 0.5f), new Vector2(0f, -30f), new Vector2(840f, 640f));
            var ribbon = UIKit.Panel(panel, "yellow", new Vector2(0.5f, 1f), new Vector2(0f, 10f), new Vector2(520f, 100f));
            UIKit.Text(ribbon.transform, "SETTINGS", 40f, new Vector2(0.5f, 0.5f), new Vector2(0f, 4f), new Vector2(500f, 80f), TextStyle.Dark);

            var d = SaveSystem.Data;
            float y = 170f;
            UIKit.Text(panel, "MUSIC", 28f, new Vector2(0.5f, 0.5f), new Vector2(-230f, y), new Vector2(300f, 50f), TextStyle.Dark, null, TextAlignmentOptions.Left);
            var music = UIKit.Slider(panel, new Vector2(0.5f, 0.5f), new Vector2(150f, y), 380f, d.music, v => { d.music = v; });
            y -= 100f;
            UIKit.Text(panel, "SOUND", 28f, new Vector2(0.5f, 0.5f), new Vector2(-230f, y), new Vector2(300f, 50f), TextStyle.Dark, null, TextAlignmentOptions.Left);
            UIKit.Slider(panel, new Vector2(0.5f, 0.5f), new Vector2(150f, y), 380f, d.sfx, v => { d.sfx = v; AudioManager.I?.Play("tick", 0.6f); });
            y -= 100f;
            UIKit.Text(panel, "SHAKE", 28f, new Vector2(0.5f, 0.5f), new Vector2(-230f, y), new Vector2(300f, 50f), TextStyle.Dark, null, TextAlignmentOptions.Left);
            var shakeBtn = UIKit.Button(panel, d.screenShake ? "ON" : "OFF", "blue", new Vector2(0.5f, 0.5f), new Vector2(150f, y), new Vector2(260f, 80f), null, null, 28f, "switch");
            var shakeLabel = shakeBtn.GetComponentInChildren<TextMeshProUGUI>();
            shakeBtn.onClick.AddListener(() =>
            {
                d.screenShake = !d.screenShake;
                shakeLabel.text = d.screenShake ? "ON" : "OFF";
                if (d.screenShake) CameraRig.I?.Shake(0.3f);
            });

            if (!fromPause)
                UIKit.Button(panel, "RESET", "red", new Vector2(0.5f, 0f), new Vector2(-200f, 80f), new Vector2(300f, 90f), ConfirmReset, null, 28f, "back");
            UIKit.Button(panel, "DONE", "green", new Vector2(0.5f, 0f), new Vector2(fromPause ? 0f : 200f, 80f), new Vector2(300f, 90f), CloseSettings, UIArt.Check, 30f, "confirm");
            UIKit.PopIn(panel);
            Select(music);
        }

        public void CloseSettings()
        {
            if (m_Settings == null) return;
            SaveSystem.Save();
            Destroy(m_Settings);
            m_Settings = null;
            if (m_Pause != null) Select(m_Pause.GetComponentInChildren<Button>());
        }

        void ConfirmReset() => Confirm("RESET ALL PROGRESS?", "STARS AND TIMES ARE LOST. COINS AND BOUGHT HEROES STAY.", "YES", "red", () =>
        {
            SaveSystem.ResetProgress();
            CloseSettings();
            ShowMenu(MenuScreen.Title);
            Toast("PROGRESS RESET");
        });

        /// <summary>Small yes/no popup. 'No' (or Back/Escape) closes it.</summary>
        void Confirm(string title, string body, string yesLabel, string yesColor, System.Action onYes)
        {
            if (m_Confirm != null) Destroy(m_Confirm);
            var root = UIKit.Stretch(m_PopupLayer, "Confirm");
            m_Confirm = root.gameObject;
            UIKit.Dim(root, 0.6f);
            var panel = UIKit.Rect(root, "Panel", new Vector2(0.5f, 0.5f), Vector2.zero, new Vector2(760f, 440f));
            UIKit.Panel(panel, "panel", new Vector2(0.5f, 0.5f), Vector2.zero, new Vector2(760f, 440f));
            UIKit.Text(panel, title, 38f, new Vector2(0.5f, 0.5f), new Vector2(0f, 120f), new Vector2(700f, 60f), TextStyle.Dark, new Color32(194, 58, 76, 255));
            UIKit.Text(panel, body, 24f, new Vector2(0.5f, 0.5f), new Vector2(0f, 40f), new Vector2(700f, 60f), TextStyle.Dark);
            var no = UIKit.Button(panel, "NO", "grey", new Vector2(0.5f, 0f), new Vector2(-160f, 95f), new Vector2(260f, 96f), () => { Destroy(m_Confirm); m_Confirm = null; }, null, 32f, "back");
            UIKit.Button(panel, yesLabel, yesColor, new Vector2(0.5f, 0f), new Vector2(160f, 95f), new Vector2(260f, 96f), () =>
            {
                Destroy(m_Confirm);
                m_Confirm = null;
                onYes?.Invoke();
            }, null, 32f, "confirm");
            UIKit.PopIn(panel);
            Select(no);
        }
