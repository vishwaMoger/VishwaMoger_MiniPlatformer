            touchBtn.onClick.AddListener(() =>
            {
                d.touchControls = (d.touchControls + 1) % 3;
                touchLabel.text = touchNames[d.touchControls];
                RefreshTouchControls();
            });
            y -= 100f;
            UIKit.Text(panel, "SHAKE", 28f, new Vector2(0.5f, 0.5f), new Vector2(-230f, y), new Vector2(300f, 50f), TextStyle.Dark, null, TextAlignmentOptions.Left);
