        void BrowseWorld(int dir)
        {
            m_BrowseWorld = Mathf.Clamp(m_BrowseWorld + dir, 0, LevelCatalog.Worlds.Length - 1);
            SaveSystem.Data.lastWorld = m_BrowseWorld;
            ShowMenu(MenuScreen.LevelSelect);
        }

        Button LevelCard(Transform parent, int level, bool unlocked, Vector2 pos)
        {
            var size = new Vector2(360f, 420f);
            var img = UIKit.Panel(parent, unlocked ? "card" : "dim_card", new Vector2(0.5f, 0.5f), pos, size, "Level" + level);
            img.raycastTarget = true;
            var btn = img.gameObject.AddComponent<Button>();
            btn.transition = Selectable.Transition.ColorTint;
            var colors = btn.colors;
            colors.highlightedColor = new Color(1f, 1f, 0.9f);
            colors.pressedColor = new Color(0.85f, 0.85f, 0.8f);
            colors.disabledColor = new Color(0.8f, 0.8f, 0.85f);
            colors.selectedColor = new Color(1f, 1f, 0.9f);
            btn.colors = colors;
            btn.interactable = unlocked;
            var fx = img.gameObject.AddComponent<UIButtonFX>();
            fx.sound = "confirm";
            int captured = level;
            btn.onClick.AddListener(() => Game.I.PlayLevel(captured));

            var header = UIKit.Panel(img.transform, unlocked ? "green" : "track", new Vector2(0.5f, 1f), new Vector2(0f, -70f), new Vector2(300f, 110f), "Header");
            UIKit.Text(header.transform, LevelCatalog.Code(level), 54f, new Vector2(0.5f, 0.5f), new Vector2(0f, 6f), new Vector2(300f, 90f), TextStyle.Heading);

            if (!unlocked)
            {
                UIKit.Image(img.transform, UIArt.Lock, new Vector2(0.5f, 0.5f), new Vector2(0f, -20f), new Vector2(96f, 112f));
                UIKit.Text(img.transform, "LOCKED", 26f, new Vector2(0.5f, 0f), new Vector2(0f, 70f), new Vector2(320f, 40f), TextStyle.Dark, new Color32(70, 70, 90, 255));
                return btn;
            }

            UIKit.Text(img.transform, LevelCatalog.LevelNames[level].ToUpperInvariant(), 22f, new Vector2(0.5f, 0.5f), new Vector2(0f, 30f), new Vector2(320f, 70f), TextStyle.Dark);
            int mask = SaveSystem.Data.stars[level];
            for (int s = 0; s < 3; s++)
            {
                bool got = (mask & (1 << s)) != 0;
                var star = UIKit.Image(img.transform, got ? UIArt.Star : UIArt.StarEmpty, new Vector2(0.5f, 0.5f), new Vector2((s - 1) * 84f, -60f), new Vector2(72f, 72f));
                if (got) star.gameObject.AddComponent<UIWave>().single = true;
            }
            var best = SaveSystem.Data.bestTime[level];
            UIKit.Image(img.transform, UIArt.Clock, new Vector2(0.5f, 0f), new Vector2(-100f, 64f), new Vector2(36f, 36f)).color = new Color32(90, 60, 70, 255);
            UIKit.Text(img.transform, UIKit.FormatTime(best), 24f, new Vector2(0.5f, 0f), new Vector2(24f, 64f), new Vector2(240f, 40f), TextStyle.Dark);
            return btn;
        }

