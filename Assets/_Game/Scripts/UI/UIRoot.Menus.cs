        public void HideMenus()
        {
            Clear(m_MenuLayer);
            ClearSnapshot();
            CloseSettings();
            if (m_Confirm != null) Destroy(m_Confirm);
            CloseMetaSilently();
            m_TitleSide = null;
        }

        public void ShowMenu(MenuScreen screen, int world = -1)
        {
            HideMenus();
            m_Screen = screen;
            if (world >= 0) m_BrowseWorld = world;
            switch (screen)
            {
                case MenuScreen.Title: BuildTitle(); break;
                case MenuScreen.LevelSelect: BuildLevelSelect(); break;
                case MenuScreen.Characters: BuildCharacters(); break;
            }
        }

        public void MenuBack()
        {
            if (m_Confirm != null) { Destroy(m_Confirm); return; }
            if (m_Meta != null) { if (!m_Spinning) CloseMeta(); return; }
            if (m_Settings != null) { CloseSettings(); return; }
            if (m_Screen != MenuScreen.Title) { AudioManager.I?.Play("back", 0.6f); ShowMenu(MenuScreen.Title); }
            else if (CanQuit) ConfirmQuit();
        }

