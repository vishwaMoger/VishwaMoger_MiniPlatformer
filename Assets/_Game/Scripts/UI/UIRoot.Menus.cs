            var lvBadge = UIKit.Panel(play.transform, "yellow", new Vector2(1f, 1f), new Vector2(-12f, 6f), new Vector2(170f, 46f), "Badge");
            UIKit.Text(lvBadge.transform, "LEVEL " + next, 17f, new Vector2(0.5f, 0.5f), new Vector2(0f, 2f), new Vector2(170f, 30f), TextStyle.Dark);
            lvBadge.transform.localRotation = Quaternion.Euler(0f, 0f, -6f);
            // the daily puzzle: new for everyone every day
            var run = UIKit.Button(col, "DAILY PUZZLE", "purple", new Vector2(0.5f, 1f), new Vector2(0f, -188f), new Vector2(430f, 100f),
