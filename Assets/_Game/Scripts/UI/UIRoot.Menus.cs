        void BuildCharacters()
        {
            var root = UIKit.Stretch(m_MenuLayer, "Characters");
            var back = UIKit.IconButton(root, UIArt.Arrow(2), "grey", new Vector2(0f, 1f), new Vector2(100f, -90f), 110f, () => ShowMenu(MenuScreen.Title), "back");
            var title = UIKit.Text(root, "CHOOSE YOUR HERO", 52f, new Vector2(0.5f, 1f), new Vector2(0f, -100f), new Vector2(1400f, 90f), TextStyle.Title, UIKit.Gold);
            UIKit.SlideIn(title.rectTransform, new Vector2(0f, 120f));
            int total = SaveSystem.TotalStars();
            Button first = null;
            int nextLocked = -1; // only the next hero in line can be unlocked early with a video
            for (int i = 0; i < LevelCatalog.Characters.Length && nextLocked < 0; i++) if (!SaveSystem.HeroUnlocked(i)) nextLocked = i;
            for (int i = 0; i < LevelCatalog.Characters.Length; i++)
            {
                var c = LevelCatalog.Characters[i];
                bool unlocked = SaveSystem.HeroUnlocked(i);
                bool selected = SaveSystem.Data.character == i;
                var card = UIKit.Panel(root, selected ? "panel" : "card", new Vector2(0.5f, 0.5f), new Vector2((i - 1.5f) * 400f, -20f), new Vector2(360f, 520f), "Hero" + i);
                UIKit.Panel(card.transform, "inset", new Vector2(0.5f, 1f), new Vector2(0f, -150f), new Vector2(300f, 240f));
                var preview = UIKit.Image(card.transform, GameAssets.I.Sprite(c.folder + "/Idle"), new Vector2(0.5f, 1f), new Vector2(0f, -150f), new Vector2(224f, 224f), "Preview");
                var anim = preview.gameObject.AddComponent<UIImageAnim>();
                anim.SetFrames(GameAssets.I.Frames(c.folder + (selected ? "/Run" : "/Idle")));
                if (!unlocked) preview.color = new Color(0.1f, 0.08f, 0.15f, 1f);
                UIKit.Text(card.transform, c.name.ToUpperInvariant(), 28f, new Vector2(0.5f, 0.5f), new Vector2(0f, -40f), new Vector2(340f, 50f), TextStyle.Dark);

                if (unlocked)
                {
                    int captured = i;
                    var b = UIKit.Button(card.transform, selected ? "READY!" : "SELECT", selected ? "yellow" : "green", new Vector2(0.5f, 0f), new Vector2(0f, 90f), new Vector2(280f, 96f), () =>
                    {
                        SaveSystem.Data.character = captured;
                        SaveSystem.Save();
                        ShowMenu(MenuScreen.Characters);
                    }, selected ? UIArt.Check : null, 30f, "confirm");
                    if (selected || first == null) first = b;
                }
                else
                {
                    UIKit.Image(card.transform, UIArt.Lock, new Vector2(0.5f, 1f), new Vector2(0f, -150f), new Vector2(84f, 98f));
                    bool offerAd = i == nextLocked && Platform.RewardedAvailable;
                    float starY = offerAd ? 170f : 90f;
                    UIKit.Image(card.transform, UIArt.Star, new Vector2(0.5f, 0f), new Vector2(-60f, starY), new Vector2(56f, 56f));
                    UIKit.Text(card.transform, $"{total}/{c.starsRequired}", 28f, new Vector2(0.5f, 0f), new Vector2(40f, starY), new Vector2(200f, 50f), TextStyle.Dark);
                    if (offerAd)
                    {
                        // optional shortcut: stars still unlock every hero for free
                        int captured = i;
                        var b = UIKit.Button(card.transform, "UNLOCK", "purple", new Vector2(0.5f, 0f), new Vector2(0f, 80f), new Vector2(280f, 88f),
                            () => UnlockHeroWithAd(captured), UIArt.Video, 28f, "confirm");
                        if (first == null) first = b;
                    }
                }
                UIKit.SlideIn(card.rectTransform, new Vector2(0f, -80f), 0.05f + i * 0.07f);
            }
            UIKit.Text(root, "EARN STARS TO UNLOCK NEW HEROES FOR FREE", 20f, new Vector2(0.5f, 0f), new Vector2(0f, 60f), new Vector2(1400f, 30f), TextStyle.Body, new Color(1, 1, 1, 0.8f));
            Select(first != null ? first : back);
        }

        void UnlockHeroWithAd(int hero)
        {
            if (Platform.AdPlaying) return;
            Platform.Rewarded(() =>
            {
                SaveSystem.Data.heroAdUnlocks |= 1 << hero;
                SaveSystem.Data.character = hero;
                SaveSystem.Save();
                AudioManager.I?.Play("unlock", 0.9f);
                if (m_Screen == MenuScreen.Characters) ShowMenu(MenuScreen.Characters);
                Toast($"NEW HERO: {LevelCatalog.Characters[hero].name.ToUpperInvariant()}!");
                Platform.HappyTime();
            }, () => Toast("NO VIDEO RIGHT NOW. TRY AGAIN LATER!"));
        }

