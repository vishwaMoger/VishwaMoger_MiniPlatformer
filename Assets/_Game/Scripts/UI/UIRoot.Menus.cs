        void BuildTitle()
        {
            var root = UIKit.Stretch(m_MenuLayer, "Title");

            // fruit floating around the logo
            string[] fruitKinds = { "Apple", "Cherries", "Strawberry", "Pineapple", "Bananas", "Orange", "Kiwi", "Melon" };
            Vector2[] fruitPos =
            {
                new Vector2(-860, -140), new Vector2(870, -130), new Vector2(-700, -480), new Vector2(710, -470),
                new Vector2(-880, -330), new Vector2(890, -320), new Vector2(-520, -600), new Vector2(530, -610),
            };
            for (int i = 0; i < fruitPos.Length; i++)
            {
                float size = i >= 6 ? 84f : 120f;
                var f = UIKit.Image(root, GameAssets.I.Sprite("PA1/Items/Fruits/" + fruitKinds[i]), new Vector2(0.5f, 1f), fruitPos[i], new Vector2(size, size), "Fruit" + i);
                f.gameObject.AddComponent<UIImageAnim>().SetFrames(GameAssets.I.Frames("PA1/Items/Fruits/" + fruitKinds[i]));
                UIFloat.Add(f.gameObject, UIFloat.Mode.Bob, 1.2f + i * 0.13f, 1f, i * 1.7f);
                UIKit.PopIn(f.rectTransform, 0.6f + i * 0.06f, 0.4f);
            }

            // game logo (generated by Tools > Fruit Quest > Generate Branding)
            var logoSprite = GameAssets.I.logo;
            RectTransform logoRt;
            if (logoSprite != null)
            {
                logoRt = UIKit.Rect(root, "LogoRoot", new Vector2(0.5f, 1f), new Vector2(0f, -250f), new Vector2(1400f, 400f));
                var logoImg = UIKit.Image(logoRt, logoSprite, new Vector2(0.5f, 0.5f), Vector2.zero, new Vector2(1400f, 400f), "Logo");
                logoImg.preserveAspect = true;
                logoImg.gameObject.AddComponent<UILogoMotion>();
            }
            else
            {
                logoRt = UIKit.Text(root, "FRUIT QUEST", 124f, new Vector2(0.5f, 1f), new Vector2(0f, -210f), new Vector2(1400f, 180f), TextStyle.Title, UIKit.Gold).rectTransform;
            }
            // drop in from above with a squashy landing
            var logoTarget = logoRt.anchoredPosition;
            var logoStart = logoTarget + new Vector2(0f, 520f);
            logoRt.anchoredPosition = logoStart;
            Tween.To(logoRt, 0.9f, k =>
            {
                logoRt.anchoredPosition = Vector2.LerpUnclamped(logoStart, logoTarget, Ease.OutBack(k));
                float squash = k > 0.55f ? Mathf.Sin((k - 0.55f) / 0.45f * Mathf.PI) * 0.06f : 0f;
                logoRt.localScale = new Vector3(1f + squash, 1f - squash, 1f);
            }, x => x, true, null, 0.1f);

            // twinkle particles scattered around the logo
            for (int i = 0; i < 9; i++)
            {
                float ang = i / 9f * Mathf.PI * 2f + 0.4f;
                var pos = new Vector2(Mathf.Cos(ang) * (720f + (i % 3) * 50f), -250f + Mathf.Sin(ang) * (190f + (i % 2) * 40f));
                var tw = UIKit.Image(root, UIArt.Twinkle, new Vector2(0.5f, 1f), pos, Vector2.one * (38f + (i % 3) * 16f), "Twinkle" + i);
                UIFloat.Add(tw.gameObject, UIFloat.Mode.Twinkle, 0.45f + (i % 4) * 0.08f, 1f, i * 0.37f);
            }

            var col = UIKit.Rect(root, "Buttons", new Vector2(0.5f, 0.5f), new Vector2(0f, -210f), new Vector2(520f, 520f));
            var play = UIKit.Button(col, "PLAY", "green", new Vector2(0.5f, 1f), new Vector2(0f, -60f), new Vector2(460f, 120f),
                () => ShowMenu(MenuScreen.LevelSelect, SaveSystem.Data.lastWorld), UIArt.Play, 48f, "confirm");
            AddShine(play, 460f);
            play.GetComponent<UIButtonFX>().pulse = 1f;
            var chars = UIKit.Button(col, "HEROES", "blue", new Vector2(0.5f, 1f), new Vector2(0f, -196f), new Vector2(420f, 96f),
                () => ShowMenu(MenuScreen.Characters), null, 34f);
            var settings = UIKit.Button(col, "SETTINGS", "yellow", new Vector2(0.5f, 1f), new Vector2(0f, -304f), new Vector2(420f, 96f),
                () => OpenSettings(false), UIArt.Gear, 34f);
            Button quit = null;
            if (Application.platform != RuntimePlatform.WebGLPlayer)
                quit = UIKit.Button(col, "QUIT", "red", new Vector2(0.5f, 1f), new Vector2(0f, -412f), new Vector2(420f, 96f), ConfirmQuit, UIArt.Close, 34f, "back");
            int i2 = 0;
            foreach (var b in new[] { play, chars, settings, quit })
                if (b != null) UIKit.SlideIn((RectTransform)b.transform, new Vector2(0f, -60f), 0.35f + 0.08f * i2++, 0.45f);

            // star counter
            var stars = UIKit.Rect(root, "Stars", new Vector2(0f, 0f), new Vector2(210f, 70f), new Vector2(380f, 90f));
            UIKit.Panel(stars, "glass", new Vector2(0.5f, 0.5f), Vector2.zero, new Vector2(340f, 90f));
