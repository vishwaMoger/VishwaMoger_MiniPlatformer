            y -= 100f;
            UIKit.Text(panel, "TOUCH PAD", 28f, new Vector2(0.5f, 0.5f), new Vector2(-230f, y), new Vector2(300f, 50f), TextStyle.Dark, null, TextAlignmentOptions.Left);
            string[] touchNames = { "AUTO", "ON", "OFF" };
            TextMeshProUGUI touchLabel = null;
            var touchBtn = UIKit.Button(panel, touchNames[d.touchControls], "blue", new Vector2(0.5f, 0.5f), new Vector2(150f, y), new Vector2(260f, 80f), null, null, 28f, "switch");
